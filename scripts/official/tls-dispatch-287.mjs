import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import ts from 'typescript'
const repo = path.resolve(import.meta.dirname, '../..')
const root = path.resolve(repo, '../.work/official-modules-2.1.287/darwin-arm64')
const bytes = fs.readFileSync(path.join(root, 'manifest.json'))
const manifest = JSON.parse(bytes)
const sha = x => crypto.createHash('sha256').update(x).digest('hex')
const pin = JSON.parse(fs.readFileSync(path.join(repo, 'src/memdir/officialMemoryFormat287/provenance.json'))).platforms.find(p => p.platform === 'darwin-arm64')
if (manifest.version !== '2.1.287' || manifest.platform !== 'darwin-arm64' || sha(bytes) !== pin.manifestSha256) throw Error('Unpinned manifest')
const rows = []
for (const [file, names] of [
  ['chunk-mbfze585.js', ['ku']],
  ['chunk-wj72kvg2.js', ['kbt', 'p7r']],
  ['chunk-09m4fzsj.js', ['eI']],
  ['chunk-4s38z9x2.js', ['Le']],
  ['chunk-15vd7hmp.js', ['o', 'n', 'hL']],
  ['chunk-wrxh9xyj.js', ['i', 'd', 'jAn', 'm', 'p', 'u', 'o', 'R', 'r7r', 'o7r', 'NVt']],
]) {
  const entry = manifest.modules.find(m => m.path === file)
  const raw = fs.readFileSync(path.join(root, 'raw', file))
  if (!entry || raw.length !== entry.length || sha(raw) !== entry.sha256) throw Error(`Invalid module ${file}`)
  const ast = ts.createSourceFile(file, new TextDecoder('utf8', {fatal:true}).decode(raw), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const nodes = ast.statements.flatMap(node => ts.isVariableStatement(node) ? [...node.declarationList.declarations] : [node])
  for (const name of names) {
    const matches = nodes.filter(n => n.name?.getText(ast) === name)
    if (matches.length !== 1) throw Error(`Ambiguous declaration ${file}/${name}`)
    const node = matches[0], source = node.getText(ast)
    rows.push({file, name, start:node.getStart(ast), end:node.end, moduleLength:entry.length, moduleSha256:entry.sha256,
      sha256:sha(source), source, variable:ts.isVariableDeclaration(node)})
  }
}
// Original files have separate lexical scopes (notably the two `o` bindings).
const emit = file => rows.filter(r => r.file === file).map(r => `${r.variable ? 'var ' : ''}${r.source}${r.variable ? ';' : ''}`).join('\n')
const dispatch = `// Verbatim 2.1.287 TLS-aware dispatch declarations; generated by tls-dispatch-287.mjs.\nexport function createNativeTlsDispatch287(ports){\nconst {Bun,globalThis,iA,cD,k,at}=ports;\n${emit('chunk-mbfze585.js')}\n${emit('chunk-wj72kvg2.js')}\nconst NVt=(()=>{\n${emit('chunk-4s38z9x2.js')}\nconst hL=(()=>{\n${emit('chunk-15vd7hmp.js')}\nreturn hL;})();\n${emit('chunk-wrxh9xyj.js')}\nreturn NVt;})();\n${emit('chunk-09m4fzsj.js')}\nreturn {fetch:eI};\n}\n`
const out = path.join(repo, 'src/utils/officialTlsDispatch287')
const files = {'native.js':dispatch, 'provenance.json':JSON.stringify({version:'2.1.287',platform:'darwin-arm64',manifestSha256:sha(bytes),offsetUnit:'UTF-16 code units',
 scope:'Complete eI/p7r/kbt/NVt dispatch closure; TLS material and host-state accessors are application ports. No TLS library/session ticket implementation recovered.',rows},null,2)+'\n'}
if (!process.argv.includes('--check')) fs.mkdirSync(out,{recursive:true})
for (const [file,value] of Object.entries(files)) {
 if (process.argv.includes('--check')) {if(fs.readFileSync(path.join(out,file),'utf8')!==value)throw Error(`Stale ${file}`)}
 else fs.writeFileSync(path.join(out,file),value)
}
console.log(JSON.stringify({declarations:rows.length,manifestSha256:sha(bytes)}))
