function captureHandlers() {
  const file = 'chunk-r4xrzyvn.js'
  const raw = fs.readFileSync(path.join(root, 'darwin-arm64/raw', file), 'utf8')
  if (manifest.modules.find(m => m.path === file)?.sha256 !== sha(raw)) throw Error('Hash mismatch: ' + file)
  const source = ts.createSourceFile(file, raw, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const names = new Set(['get_hooks_listing', 'list_permission_rules', 'reload_skills', 'reload_output_styles'])
  function walk(node) {
    if (ts.isIfStatement(node)) {
      for (const name of names) if (node.expression.getText(source) === `T.request.subtype==="${name}"`) {
        const text = node.thenStatement.getText(source)
        handlers.push({file, name, moduleSha256: sha(raw), offset: node.thenStatement.getStart(source), sha256: sha(text), text})
      }
    }
    ts.forEachChild(node, walk)
  }
  walk(source)
  if (handlers.length !== names.size) throw Error('Expected four print handlers')
}
function select(file, names) {
  const raw = fs.readFileSync(path.join(root, 'darwin-arm64/raw', file), 'utf8')
  if (manifest.modules.find(m => m.path === file)?.sha256 !== sha(raw)) throw Error('Hash mismatch: ' + file)
  const source = ts.createSourceFile(file, raw, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  return names.map(symbol => {
    let node
    for (const statement of source.statements) {
      if (statement.name?.text === symbol) node = statement
      if (ts.isVariableStatement(statement)) for (const d of statement.declarationList.declarations) if (d.name.getText(source) === symbol) node = d
    }
    if (!node) throw Error('Missing ' + symbol)
    const text = node.getText(source)
    records.push({file, notice: raw.slice(0, raw.indexOf('import')), moduleSha256: sha(raw), symbol, declarationSha256: sha(text), declaration: text})
    return (ts.isVariableDeclaration(node) ? 'var ' + text + ';' : text)
  }).join('\n')
}
